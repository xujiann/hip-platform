    pend = [r for r in rows if r['终审结论'] == '待人工签认']
    out_rows, counts = [], {}
    for r in pend:
        text = r['参数摘要'].replace('\n', ' ')
        verdict, evidence = '真待议', '规则未命中，须项目组人工裁决'
        for pat, v, e in RULES:
            if re.search(pat, text):
                verdict, evidence = v, e
                break
        counts[verdict] = counts.get(verdict, 0) + 1
        out_rows.append({'序号': r['序号'], '参数摘要': text[:200], '建议结论': verdict, '证据/理由': evidence})

    dst = ROOT / 'docs' / '验收' / '待签认证据包.csv'
    with open(dst, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=['序号', '参数摘要', '建议结论', '证据/理由'])
        w.writeheader()
        w.writerows(out_rows)
    print('输出', dst, '共', len(out_rows), '条')
    for k, v in sorted(counts.items(), key=lambda x: -x[1]):
        print(f'  {k}: {v}')


