# 表格分隔符/空壳行（doc 转换残渣）直接判定
def is_noise(s):
    t = s.replace('<!-- -->', '').strip()
    return len(t.strip('+-| ')) < 4

with open(SRC, encoding='utf-8-sig') as f:
    reader = csv.reader(f)
    header = next(reader)
    rows = list(reader)

if '终审' not in header:
    header.append('终审')
    header.append('终审说明')

IDX_SUMMARY, IDX_VERDICT = 3, 6
stats = collections.Counter()
out_rows = []
for r in rows:
    while len(r) < len(header):
        r.append('')
    if r[IDX_VERDICT] != '待人工评估':
        r[len(header) - 2] = r[len(header) - 2] or ''
        continue
    summary = r[IDX_SUMMARY]
    verdict, note = '待人工签认', ''
    if is_noise(summary):
        verdict, note = '格式行(非参数)', 'doc 转换产生的表格分隔残渣，不计入参数'
    else:
        for kws, v, n in RULES:
            if any(k in summary for k in kws):
                verdict, note = v, n
                break
    r[len(header) - 2] = verdict
    r[len(header) - 1] = note
    stats[verdict] += 1
    out_rows.append([r[0], summary[:200], verdict, note])

with open(SRC, 'w', newline='', encoding='utf-8-sig') as f:
    w = csv.writer(f)
    w.writerow(header)
    w.writerows(rows)

with open(DST, 'w', newline='', encoding='utf-8-sig') as f:
    w = csv.writer(f)
    w.writerow(['序号', '参数摘要', '终审结论', '对应功能/说明'])
    w.writerows(out_rows)

total = sum(stats.values())
print(f'终审二级评审完成（待评 {total} 条）：')
for k, v in stats.most_common():
    print(f'  {k}: {v} ({v * 100 // total}%)')
print(f'清单已导出：{DST}（「待人工签认」项须项目组逐条确认）')
