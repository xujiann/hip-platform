    summary = r[3]
    if any(k in summary for k in EXTERNAL_KEYWORDS):
        verdict = '涉外部条件'
    elif any(k in summary for k in PRODUCT_KEYWORDS):
        verdict = '属配套产品参数'
    elif any(k in summary for k in IMPLEMENTED_KEYWORDS):
        verdict = '初评符合'
    else:
        verdict = '待人工评估'
