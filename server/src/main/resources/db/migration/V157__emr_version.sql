-- v53 车道 V1：病历修订留痕与版本管理 —— 版本表（错误码 5700–5719）
--
-- =====================================================================================
-- 【这是合规缺口，不是功能缺口】
-- =====================================================================================
-- 《电子病历应用管理规范》第二十四条要求病历修改留痕、可追溯。
-- 实测现状：`DoctorStationService:137` 与 `:941` 两处都是 `emrRepository.save(emr)`，
-- **整行覆盖**。医生保存第二次，第一次写的内容就永久消失了，库里查不到、日志里也没有。
-- 医疗纠纷举证时，「病历被改过而系统证明不了改了什么」等同于举证不能。
--
-- 所以本表的判据不是「功能好不好用」，是**「能不能证明」**。
--
-- =====================================================================================
-- 【为什么不复用 emr_amendment（V80），也不往它里面加列】
-- =====================================================================================
-- 逐字读过 V80__emr_amendment_and_frontpage.sql 与
-- DoctorStationService#amendEmr / #listAmendments 的实现，结论：
--
--   `emr_amendment` 管的是**已签名冻结病历的补正追加**——原文不动、另起一条、
--   带补正原因与补正人。它的写入前置条件是 `emr.getSignature() != null`（未签名会抛 4018），
--   语义是「这份病历已经发出去了，事后发现写错，依法追加一条更正说明」。
--
--   本表管的是**编辑过程中的版本留痕**——签名之前，医生保存了五次，
--   前四次的正文各是什么。写入前置条件恰恰相反：病历**未签名、可改**。
--
-- 两者是病历生命周期里**不同的两个环节**，不可互相替代：
--   * 拿 emr_amendment 记编辑过程 → 每次保存都要填「补正原因」，且未签名就写补正
--     与 4018 的既有语义直接打架，还会污染补正历史（法定补正记录里混进几十条草稿）；
--   * 拿本表记事后补正 → 丢掉了「原因」这个法定必填项。
-- 故**新建一张表**，emr_amendment 一个字段都不动。
--
-- =====================================================================================
-- 【铁律：迁移零条 update、零回填】
-- =====================================================================================
-- 本文件**只有 create table / create index / insert into sys_config 三类语句**，
-- 对 outp_emr、inp_medical_record、emr_amendment 及任何既有表**零 update、零 insert**。
--
-- 尤其：**不拿病历的当前内容伪造一条「初版」**。
-- 历史病历没有版本记录，那是事实——当时系统就没采集。伪造一条 version_no=1、
-- 内容等于今天的当前值、saved_at 等于今天的时间戳，会让举证材料里出现
-- **一条从未真实存在过的版本**。那不是补数据，那是造证。
-- 结果就是：本表建完是空的，历史病历查版本列表返回空数组，前端显示
-- 「本份病历在版本留痕上线前书写，无历史版本」。这句话是真的，可以拿去举证。
--
-- 表内**没有 is_example / 示例行**（与 V155 词表的处置不同）：
-- 版本表里的每一行都会被当作某个人在某个时刻写过的内容，示例行等同伪证。
--
-- =====================================================================================
-- 【只回看不回滚】
-- =====================================================================================
-- 本版提供版本列表、单版查看、任意两版结构化对比，**不提供「恢复到某一版」**。
-- 回滚会让「当前版本的责任人是谁」变得不清楚：A 写了 v3，B 一键回滚到 v1，
-- 当前正文是 A 一小时前的字、责任却记在 B 头上，还是记在 A 头上？法定病历不做这个。
-- 需要改回去，就由医师本人重新书写并保存，落成 v4——责任链完整。
-- 表结构上也没有留 restored_from 之类的列，防止后来人「顺手做一下」。

-- =====================================================================================
-- 一、版本表
-- =====================================================================================
create table emr_version (
    id           bigserial   primary key,

    -- 病历类型：OUTP 门诊病历(outp_emr) / INP 住院病历(inp_medical_record)。
    -- **沿用 emr_amendment.emr_type 的既有口径**（V80:11），不新造第三套枚举。
    emr_type     varchar(8)  not null,

    -- 关联病历主键：emr_type=OUTP → outp_emr.id；emr_type=INP → inp_medical_record.id。
    -- **刻意不加外键**：一列要指向两张表，PG 没有多态外键；
    -- 且版本留痕不应随主表行被级联删掉（病历行若被删，留痕正是唯一还能证明它存在过的东西）。
    emr_id       bigint      not null,

    -- 版本序号：同一份病历内从 1 起连续递增。由写侧在事务内取 max+1，
    -- 并发由 pg_advisory_xact_lock(5700/5701, emr_id) 串行化（见 EmrVersionService）；
    -- 下面的 unique 约束是最后一道防线，即便建议锁失效也不会出现重号。
    version_no   int         not null,

    -- 保存来源：MANUAL 医生手动保存 / AUTO 前端自动保存 / SUBMIT 提交（含签名前的定稿保存）。
    -- **新表零历史行，加 CHECK 不存在「脏类型挡住 Flyway」的风险**
    -- （与 V133:15-18 对 inp_medical_record.record_type 刻意不加 CHECK 的处置不同，
    --   那是因为那张表已有历史脏值）。这里加 CHECK 是有意的：
    --   来源标错等于把「自动保存」说成「医生亲手点了保存」，是证据链上的失真。
    source       varchar(16) not null,

    -- 内容快照：**完整全文**，不是 diff。
    -- 只存 diff 有两个致命问题：① 举证时说不清楚——律师问「第 2 版当时写的是什么」，
    -- 拿一串 @@ -3,7 +3,9 @@ 出来是答不上来的；② 原始内容一旦丢了 diff 也还原不出，
    -- 链条上任何一环缺失就全废。全文快照是自解释的，单独拎一行出来就能读。
    --
    -- 格式：JSON 对象 {字段名: 字符串值|null}，**键按字典序排序**（规范化，供 content_hash 稳定）。
    -- 用 text 存 JSON 是本仓惯例（不开 jsonb，见 V139:77 outp_emr.content_json 同样处置）。
    -- 允许为 null：病历五段全空也是一种真实状态，不许写侧拿空串替换掉。
    content      text,

    -- 快照字符数。冗余列，但让「表长多快 / 单版多大」这类容量问题
    -- 不必去读 TOAST 出来的 content 本体就能统计——统计查询不碰大字段，这是有意的。
    content_len  int         not null default 0,

    -- 规范化 JSON 的 SHA-256（小写 hex，64 字符）。用途只有一个：
    -- 与上一版比对，**内容逐字节相同就不落新版**（自动保存每 30 秒一次，
    -- 医生泡杯茶回来能刷出 20 条一模一样的版本，那不是留痕，那是噪音）。
    -- 见 EmrVersionService 的 dedup 开关；它不是安全哈希用途，不做防篡改声明。
    content_hash varchar(64),

    -- 保存人 sys_user.id。**可空**：服务层直调、无登录上下文的既有单测与 E2E
    -- （DoctorStationService.saveEmr 的 doctorId 本来就允许为 null）在这里就是 null。
    -- 查询侧如实回 null，**不做任何"回填成当班医生"的猜测**——猜错了就是把责任安在别人头上。
    -- 加外键是有意的：saved_by 指向一个真实存在的用户，这一点要在库层面可证。
    saved_by     bigint      references sys_user (id),

    -- 保存时刻。写侧一律 `Instant.now().truncatedTo(MICROS)` 后显式传入，
    -- **不依赖下面的 default now()**（default 只是给直连 SQL 兜底）。
    -- 理由：PG timestamptz 只存微秒且按四舍五入落盘，Java Instant 带纳秒，
    -- 不截断会产生「写进去 12:00:00.0000005、读回来 12:00:00.000001」的差 100ns 假越界。
    -- 本仓已被这个根因炸过四次（见 7b56a96 / 31da46a 两次扫尾提交）。
    saved_at     timestamptz not null default now(),

    -- 业务日（Asia/Shanghai），由 Java 侧 BusinessDates.today() 显式传入。
    -- **不是 date(saved_at)**：DB 会话时区与业务时区是两套口径，跨 00:00–08:00 的夜班
    -- 两者会差一天（1.1.9 已付过学费）。这一列存在的意义是给将来的归档/分区
    -- 一个不受会话时区影响的裁剪键。
    saved_on     date        not null,

    constraint chk_emr_version_type   check (emr_type in ('OUTP', 'INP')),
    constraint chk_emr_version_source check (source in ('MANUAL', 'AUTO', 'SUBMIT')),
    constraint chk_emr_version_no     check (version_no >= 1),

    -- 同一份病历内版本号唯一。这既是数据完整性约束，也是**唯一的查询索引**：
    -- 列表/单版/对比三类查询全是 `where emr_type = ? and emr_id = ?`（+ version_no），
    -- 正好走这个 btree 的最左前缀；倒序列表由 PG 反向扫描同一个索引完成。
    -- **刻意不再建第二个索引**——每多一条索引就是每次保存多一次写放大，
    -- 而留痕做得让医生嫌卡，最后一定会被关掉。
    constraint uk_emr_version_no      unique (emr_type, emr_id, version_no)
);

-- content 是 text，PG 默认 storage = EXTENDED：超过约 2KB 自动 pglz 压缩并转存 TOAST。
-- **所以应用层不再做二次压缩**，这是有意的取舍：
--   * 压了的 bytea 用 SQL 读不出来、DBA 导不出来、举证时得先跑一段程序才能看见内容，
--     那就把「可自证」这个唯一的设计目标给毁了；
--   * PG 的行内压缩已经拿到了绝大部分收益（中文病历文本 pglz 实测压到 40–60%），
--     再压一层的边际收益远小于「快照不再是人类可读」的代价。
-- 这句话不是注释里的口号，storage 就是默认值，此处只是把决定写下来。

-- =====================================================================================
-- 二、配置（三态 gate + 两个容量旋钮）
-- =====================================================================================
-- gate 三态 off|warn|block，**默认 warn，坏值回落 warn**（不回落 off）。
--
-- 这里的三态与 CDSS 那类「拦截 gate」语义不同，必须说清楚，否则运维会按错的心智去调：
--   * off   —— 完全不落版本。**逃生口**，给「留痕把生产写崩了」这种极端情况用。
--               开在这一档意味着本版的合规声明当场失效，settings 端点会把它明说出来。
--   * warn  —— 落版本；**万一留痕写失败（如 saved_by 指向不存在的用户、磁盘满），
--               回滚到 savepoint、记 ERROR 日志、计数器 +1，但不连累医生那一次保存**。
--               依据是铁律「既有链路不许改坏」：EMR 保存是核心写路径，
--               不能因为侧车表写不进去就让医生存不了病历。
--   * block —— 落版本；留痕写失败就**让这次保存一起失败**（5705）。
--               语义是「没有痕迹就不许留下内容」。合规要求最严的院区可以调到这一档，
--               但要接受「留痕表出问题时医生写不了病历」的后果。
insert into sys_config (cfg_key, cfg_value, remark) values
    ('emr.version.gate', 'warn',
     '病历版本留痕：off 完全不落版本（逃生口，开启即失去修改留痕的合规声明）/ '
     'warn 落版本，留痕写失败时回滚到 savepoint 并记 ERROR，不连累医生本次保存（默认）/ '
     'block 落版本，留痕写失败则本次保存一并失败（5705）。坏值回落 warn，不回落 off。')
on conflict (cfg_key) do nothing;

-- 去重：与上一版内容逐字节相同就不落新版。默认开。
-- 关掉它的唯一理由是「要证明医生在 14:03 点过一次保存键」——但那属于操作日志，
-- 不属于病历版本；内容没变的版本对举证没有任何贡献，只会让版本列表淹掉真正的修改。
insert into sys_config (cfg_key, cfg_value, remark) values
    ('emr.version.dedup', 'on',
     '版本去重：on 与上一版内容完全相同则不落新版（默认，专治前端自动保存刷屏）/ '
     'off 每次调用都落一版。关掉会让版本列表被大量无差异版本淹没，不建议。')
on conflict (cfg_key) do nothing;

-- 单版快照字符数上限。触顶时**绝不截断**（截断后的快照拿去举证等于伪证），
-- 而是按 gate 档位处理：strict 接口直接 5704 拒绝；warn 档的留痕接缝记 ERROR 后照写全文。
-- 100 万字符按 UTF-8 中文约 3MB，远超任何一份真实病历（门诊五段列宽合计 5512 字符，
-- 住院 inp_medical_record.content 自 V133 起是 text）。设这个值是为了挡住
-- 「前端把整个 base64 图片塞进正文」这类事故，不是为了限制正常书写。
insert into sys_config (cfg_key, cfg_value, remark) values
    ('emr.version.max-content-chars', '1000000',
     '单版快照字符数上限。超限**永不截断**：strict 接口返 5704 拒绝，留痕接缝（warn 档）记 ERROR 后照写全文。'
     '用于挡住「整张图 base64 塞进正文」这类事故，不是书写长度限制。')
on conflict (cfg_key) do nothing;

-- =====================================================================================
-- 三、刻意不做的事
-- =====================================================================================
-- 1) **不插 sys_menu**。本车道按分工不改 frontend/shell/src（共用目录），
--    没有配套页面。插了菜单就是给医生一个点进去 404 的死链（沿用 V155 的处置）。
--    页面需求已写进 cross_lane 交主控。
-- 2) **不分区**。分区键只能是 saved_on 或 id，而 PG 要求唯一约束必须包含分区键——
--    uk_emr_version_no (emr_type, emr_id, version_no) 会被迫变成
--    (emr_type, emr_id, version_no, saved_on)，那就**不再能保证同一份病历版本号唯一**
--    （同一份病历跨月修改会出现两个 version_no=3）。这是真代价，不是麻烦。
--    容量测算与何时该分区写在 EmrVersionService 的类注释里，届时须连同唯一约束一起重新设计。
-- 3) **不建归档表、不写清理任务**。病历是法定长期保存材料，版本留痕是病历的一部分，
--    保存年限按院内病历管理制度执行；在没有拿到院方明确年限之前，
--    写一个会删证据的定时任务是危险的。
