-- v47 写入校验收口版：体征录入服务端校验的三态 gate。
--
-- 背景：inp_vital_sign 自 V9 建表以来写路径**零服务端校验**——POST /vitals 是
-- `@RequestBody InpVitalSign` 后 setId(null) 直接 save，量程只活在前端 utils/vitals.ts。
-- v42 之前这只是脏数据；**v42 之后体温单已经能打印出纸**，API 直调写进去的 999℃
-- 会直接上法定护理文书且事后无法追溯。本版把校验收到服务端（4822/4823/4824/4825）。
--
-- ===== 为什么默认 warn 而不是 block（这条口径请勿在没有数据支撑时改掉）=====
-- 本平台此前**从无此校验**，直接 block 会让存量对接方与移动端**瞬间大面积失败**：
--   * 历史/回顾性补录的 measuredAt 早于入院时间的行，一律写不进去；
--   * PDA、床旁监护仪与服务器的时钟偏差是常态（本版留 5 分钟容差，仍挡不住偏差大的设备）；
--   * 只录出入量、六项体征全空且没填未测原因的行，是护理惯例里真实存在的形态。
-- warn 档**不拦截、照常落库，只把问题以 warnings 回带**，让护士当场看见
-- 「体温 999 已记录，请核对」，而不是像 v46 之前那样静默存进去。
-- 先让问题可见、可统计，**收紧到 block 的时机由院方按自家数据质量决定**。
-- 坏配置（写成别的字符串）在服务端回落 warn 而不是 off：宁可多提示，不可静默失效。
--
-- ===== 本迁移**只 seed 一个配置键**，不动任何表结构 =====
-- 尤其**不给 inp_vital_sign 加 CHECK 约束**、也不给 inp_medical_record.record_type 加 CHECK：
-- 试点库的历史脏数据会挡住 Flyway，迁移失败的代价远高于脏数据（v42 已定此口径，v47 沿用）。
-- 收口一律做在写入端，读侧与历史行为一字不动。

insert into sys_config (cfg_key, cfg_value, remark) values
    ('emr.gate.vital.range', 'warn',
     '体征录入服务端校验（量程4824/测量时间4825/测量部位4822/未测原因4823）：off 旁路 / warn 放行并回带 warnings（默认）/ block 硬拦')
on conflict (cfg_key) do nothing;
